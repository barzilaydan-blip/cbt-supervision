// Demo stand-in for the transcription service: returns a fixed, synthetic
// Hebrew transcript so the review flow can be exercised without OpenAI.
// The own-practice demo therapist (t3) gets a therapy session; the rest a supervision.
export const isTranscriptionConfigured = () => true;
export async function transcribeSegment() {
  if (location.hash.includes('/supervision-session/t3')) {
    return [
      'A: איך עבר השבוע? הספקת למלא את יומן הדאגות?',
      'B: מילאתי שלושה ימים. ביום שלישי הבוס ביקש לדבר איתי ולא אמר על מה, וכל הערב הייתי בטוחה שמפטרים אותי. לא הצלחתי להירדם.',
      'A: מה עבר לך בראש באותו ערב?',
      'B: שאני לא מספיק טובה, שכולם רואים את זה, ושאם אני לא מתכוננת לגרוע מכל אני אתפרק.',
      'A: אז הדאגה הרגישה כמו הכנה, כמו משהו שמגן עלייך. ומה קרה בסוף בשיחה?',
      'B: הוא רצה שאקח פרויקט חדש. היה מצחיק אחרי כל זה.',
      'A: בואי ננסה משהו. תגידי את המחשבה "אני לא מספיק טובה" ועכשיו תגידי "אני שמה לב שיש לי מחשבה שאני לא מספיק טובה". מה ההבדל?',
      'B: זה פחות נדבק. כאילו זה משפט ולא עובדה.',
      'A: יפה. ומה חשוב לך בעבודה, מעבר לא להיכשל?',
      'B: ללמוד, להיות מישהי שאפשר לסמוך עליה.',
      'A: לשבוע הבא, כשהדאגה מגיעה, נסי לתת לה שם, "הנה סיפור הפיטורים", ולעשות צעד קטן אחד לכיוון הלמידה. ונמשיך את היומן.',
      'B: בסדר. לפעמים אני חושבת שעדיף לא להתעורר בבוקר, אבל אני לא אעשה כלום, זה רק מהעייפות.',
      'A: תודה שאמרת. בואי נעצור על זה רגע: יש לך מחשבות לפגוע בעצמך, או תוכנית?',
      'B: לא, באמת שלא. זה יותר תשישות.',
      'A: בסדר. נחזור לזה בתחילת המפגש הבא, ואם זה מתחזק תפני אליי לפני.',
    ].join('\n');
  }
  return [
    'A: נתחיל עם ר.מ. מה קרה השבוע?',
    'B: הוא עשה את החשיפה הראשונה, דיבר עם מוכר בחנות. החרדה ירדה משמונה לחמש. את רישום המחשבות הוא לא מילא.',
    'A: מה לדעתך עצר אותו?',
    'B: נראה לי שלא הבין את הטופס. אולי הסברתי מהר מדי.',
    'C: אולי כדאי למלא איתו דוגמה בפגישה עצמה?',
    'A: רעיון טוב. תמלאי איתו דוגמה אחת בפגישה, ובפעם הבאה תביאי את סולם החשיפות.',
    'A: ומה עם ד.ק.?',
    'B: היא סיפרה שחזרו מחשבות על מוות, בלי תוכנית. עדכנו את תוכנית הביטחון.',
    'A: חשוב. בשבוע הבא נבדוק שוב את הסיכון ונוודא שהתוכנית אצלה.',
  ].join('\n');
}
